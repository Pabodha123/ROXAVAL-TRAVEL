// ISO-3166 alpha-2 -> flag emoji via regional indicator symbols (no image assets needed).
export function isoToFlag(iso2: string): string {
  return iso2.toUpperCase().replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt(0)));
}

